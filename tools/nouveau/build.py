#!/usr/bin/env python3
"""Assemble the /nouveau/ home page prototype (Applications John Maibwe).

    python3 tools/nouveau/build.py

Inputs (all under tools/nouveau/):
    page.html            page shell with one <!-- @section ID --> marker per section
    sections/ID.html     one HTML fragment per section
    css/base.css         design system  + css/ID.css (one per section, page order)
    js/core.js           tiny framework + js/ID.js   (one per section, page order)

Outputs (never edit them by hand, they are overwritten):
    public/nouveau/index.html
    public/assets/nouveau/nouveau.css
    public/assets/nouveau/nouveau.js
    public/nouveau/composants.html   (design-system sample, from tools/nouveau/composants.html)

Pure Python 3 standard library. Idempotent: same inputs -> byte-identical outputs.
Fails loudly (exit code 1) on a missing/duplicated marker, a missing fragment, an inline
<script>, an on* event attribute, a javascript: URL, an external image/script, or a
duplicated id attribute. Prints a page-weight report against the 700 KB budget.
"""
from __future__ import annotations

import hashlib
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent.parent
PUBLIC = REPO / "public"

# Page order. Builders: never reorder or rename without updating DESIGN.md.
SECTIONS = ["hero", "pile", "services", "apps", "donnees", "chiffres", "methode", "ponts", "contact"]

OUT_HTML = PUBLIC / "nouveau" / "index.html"
OUT_CSS = PUBLIC / "assets" / "nouveau" / "nouveau.css"
OUT_JS = PUBLIC / "assets" / "nouveau" / "nouveau.js"

BUDGET_BYTES = 700 * 1024  # excluding Google Fonts

MARKER_RE = re.compile(r"<!--\s*@section\s+([a-z0-9_-]+)\s*-->")


class BuildError(Exception):
    pass


def read(path: Path) -> str:
    if not path.is_file():
        raise BuildError(f"missing file: {path.relative_to(REPO)}")
    return path.read_text(encoding="utf-8")


def short_hash(data: str) -> str:
    return hashlib.sha256(data.encode("utf-8")).hexdigest()[:10]


def strip_comments(html: str) -> str:
    return re.sub(r"<!--.*?-->", "", html, flags=re.S)


def check_fragment(name: str, html: str) -> list[str]:
    """Return a list of CSP / safety violations found in an HTML fragment."""
    errors = []
    code = strip_comments(html)
    for m in re.finditer(r"<script\b[^>]*>", code, flags=re.I):
        tag = m.group(0)
        if "src=" not in tag.lower():
            errors.append(f"{name}: inline <script> is forbidden by the CSP: {tag}")
        elif name != "page.html":
            errors.append(f"{name}: <script> tags belong in page.html only (use js/<id>.js): {tag}")
    for m in re.finditer(r"<[a-zA-Z][^>]*?\s(on[a-z]+)\s*=", code):
        errors.append(f"{name}: event-handler attribute '{m.group(1)}=' is forbidden by the CSP")
    if re.search(r"""(href|src|action)\s*=\s*["']\s*javascript:""", code, flags=re.I):
        errors.append(f"{name}: javascript: URLs are forbidden")
    for m in re.finditer(r"""<(img|source|script|iframe|video|audio)\b[^>]*?\s(src|srcset)\s*=\s*["']\s*(https?:)?//""", code, flags=re.I):
        errors.append(f"{name}: external {m.group(1)} source is forbidden (self-host it): {m.group(0)[:90]}")
    if re.search(r"<iframe\b", code, flags=re.I):
        errors.append(f"{name}: <iframe> is not allowed")
    return errors


def build() -> None:
    page = read(HERE / "page.html")

    # 1. markers: each section exactly once, in the declared order, nothing unknown.
    found = MARKER_RE.findall(page)
    unknown = [m for m in found if m not in SECTIONS]
    if unknown:
        raise BuildError(f"page.html has unknown section marker(s): {unknown}")
    for sid in SECTIONS:
        n = found.count(sid)
        if n != 1:
            raise BuildError(f"page.html must contain the marker <!-- @section {sid} --> exactly once (found {n})")
    if found != SECTIONS:
        raise BuildError(f"page.html markers are out of order: {found} (expected {SECTIONS})")

    errors = check_fragment("page.html", page)

    # 2. fragments
    fragments = {}
    for sid in SECTIONS:
        frag = read(HERE / "sections" / f"{sid}.html").strip("\n")
        errors += check_fragment(f"sections/{sid}.html", frag)
        if not re.search(rf"""<section\b[^>]*\bid\s*=\s*["']{re.escape(sid)}["']""", frag):
            errors.append(f"sections/{sid}.html: must contain <section id=\"{sid}\" ...>")
        if not re.search(r"""\bdata-theme\s*=\s*["'](dark|ink|navy|cream|gold)["']""", frag):
            errors.append(f"sections/{sid}.html: the <section> needs data-theme=\"dark|ink|navy|cream|gold\"")
        fragments[sid] = frag

    # 3. CSS + JS bundles (page order)
    css_parts = [
        "/* GENERATED by tools/nouveau/build.py — edit tools/nouveau/css/*.css, not this file. */\n",
        "/* ===== base.css ===== */\n" + read(HERE / "css" / "base.css").strip() + "\n",
    ]
    for sid in SECTIONS:
        css_parts.append(f"\n/* ===== {sid}.css ===== */\n" + read(HERE / "css" / f"{sid}.css").strip() + "\n")
    css = "".join(css_parts)

    js_parts = [
        "/* GENERATED by tools/nouveau/build.py — edit tools/nouveau/js/*.js, not this file. */\n",
        "/* ===== core.js ===== */\n" + read(HERE / "js" / "core.js").strip() + "\n",
    ]
    for sid in SECTIONS:
        body = read(HERE / "js" / f"{sid}.js").strip()
        # Each section file gets its own scope so builders cannot collide on globals.
        js_parts.append(f"\n/* ===== {sid}.js ===== */\n;(function () {{\n'use strict';\n{body}\n}}());\n")
    js = "".join(js_parts)

    # 4. assemble the page
    blocks = {
        sid: f"<!-- ===== section: {sid} (tools/nouveau/sections/{sid}.html) ===== -->\n{fragments[sid]}"
        for sid in SECTIONS
    }
    html = MARKER_RE.sub(lambda m: blocks[m.group(1)], page)
    html = html.replace("{{CSS_VERSION}}", short_hash(css)).replace("{{JS_VERSION}}", short_hash(js))
    if "{{" in html:
        raise BuildError("page.html still contains an unreplaced {{placeholder}}")
    if not html.lstrip().lower().startswith("<!doctype html>"):
        raise BuildError("page.html must start with <!doctype html>")
    html = html.replace(
        "<!doctype html>",
        "<!doctype html>\n<!-- GENERATED by tools/nouveau/build.py — edit tools/nouveau/*, not this file. -->",
        1,
    )

    # 5. duplicate ids across the whole page
    ids = re.findall(r"""\sid\s*=\s*["']([^"']+)["']""", strip_comments(html))
    seen, dups = set(), set()
    for i in ids:
        (dups if i in seen else seen).add(i)
    if dups:
        errors.append(f"duplicate id attribute(s) in the assembled page: {sorted(dups)}")

    # 6. in-page anchors must resolve
    for target in sorted(set(re.findall(r"""href\s*=\s*["']#([^"']+)["']""", strip_comments(html)))):
        if target not in seen:
            errors.append(f"anchor href=\"#{target}\" points to no element id")

    # 6b. design-system sample page (optional): tools/nouveau/composants.html → /nouveau/composants.html
    outputs = [(OUT_HTML, html), (OUT_CSS, css), (OUT_JS, js)]
    sample = HERE / "composants.html"
    if sample.is_file():
        sample_html = sample.read_text(encoding="utf-8").replace("{{CSS_VERSION}}", short_hash(css))
        errors += check_fragment("page.html", sample_html)
        outputs.append((OUT_HTML.parent / "composants.html", sample_html))

    if errors:
        raise BuildError("\n  - " + "\n  - ".join(errors))

    # 7. write (only when content changed, so mtimes stay stable)
    for path, data in outputs:
        path.parent.mkdir(parents=True, exist_ok=True)
        if not path.exists() or path.read_text(encoding="utf-8") != data:
            path.write_text(data, encoding="utf-8")

    report(html, css)


def local_path(url: str) -> Path | None:
    url = url.split("#", 1)[0].split("?", 1)[0].strip()
    if not url.startswith("/") or url.startswith("//"):
        return None
    p = PUBLIC / url.lstrip("/")
    return p if p.is_file() else None


def report(html: str, css: str) -> None:
    code = strip_comments(html)
    urls = set()
    for m in re.finditer(r"""\s(?:src|href)\s*=\s*["']([^"']+)["']""", code):
        urls.add(m.group(1))
    for m in re.finditer(r"""srcset\s*=\s*["']([^"']+)["']""", code):
        for part in m.group(1).split(","):
            if part.strip():
                urls.add(part.strip().split()[0])
    for m in re.finditer(r"""url\(\s*["']?([^"')]+)["']?\s*\)""", css):
        urls.add(m.group(1))

    files = {}
    for u in urls:
        p = local_path(u)
        if p is not None and p.suffix.lower() != ".html" and p.name != "favicon.ico" and "apple-touch-icon" not in p.name:
            files[p] = p.stat().st_size

    html_size = len(html.encode("utf-8"))
    total = html_size + sum(files.values())
    print(f"built {OUT_HTML.relative_to(REPO)}  ({html_size/1024:.1f} KB)")
    rows = sorted(files.items(), key=lambda kv: -kv[1])
    for p, size in rows:
        print(f"  {size/1024:7.1f} KB  {p.relative_to(PUBLIC)}")
    status = "OK" if total <= BUDGET_BYTES else "OVER BUDGET"
    print(f"page weight (HTML + every local file it references, excl. Google Fonts): "
          f"{total/1024:.1f} KB / {BUDGET_BYTES/1024:.0f} KB  [{status}]")
    if total > BUDGET_BYTES:
        print("WARNING: over the 700 KB budget — compress or drop images.", file=sys.stderr)


if __name__ == "__main__":
    try:
        build()
    except BuildError as exc:
        print(f"BUILD FAILED: {exc}", file=sys.stderr)
        sys.exit(1)
